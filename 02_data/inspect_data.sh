#!/bin/bash
# ============================================================
# inspect_data.sh
# الغرض: فحص سريع لملف بيانات (CSV/JSON/TXT) دون فتحه
# الاستخدام: ./inspect_data.sh data.csv
# ============================================================

set -e

FILE=$1

if [ ! -f "$FILE" ]; then
    echo "❌ الملف غير موجود: $FILE"
    exit 1
fi

echo "======================================================"
echo "🔍 فحص الملف: $FILE"
echo "======================================================"

# معلومات عامة
echo ""
echo "📊 معلومات عامة:"
echo "   الحجم: $(du -h "$FILE" | cut -f1)"
echo "   عدد الأسطر: $(wc -l < "$FILE")"
echo "   عدد الكلمات: $(wc -w < "$FILE")"

# عرض أول 5 أسطر
echo ""
echo "👀 أول 5 أسطر:"
head -n 5 "$FILE"

# عرض آخر 3 أسطر
echo ""
echo "👀 آخر 3 أسطر:"
tail -n 3 "$FILE"

# الأعمدة (إذا كان CSV)
if [[ "$FILE" == *.csv ]]; then
    echo ""
    echo "📋 عدد الأعمدة (بناءً على السطر الأول):"
    head -n 1 "$FILE" | awk -F',' '{print NF " عمود"}'
    
    echo ""
    echo "📋 أسماء الأعمدة:"
    head -n 1 "$FILE" | tr ',' '\n' | nl
fi

# فحص القيم الفارغة (إذا كان CSV)
if [[ "$FILE" == *.csv ]]; then
    echo ""
    echo "❓ عدد القيم الفارغة (تقريبي):"
    grep -c ",," "$FILE" || echo "0"
fi

echo ""
echo "✅ انتهى الفحص."
